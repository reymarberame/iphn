import React, { Fragment, useState } from 'react';
import { Head, router } from '@inertiajs/react';
import {
    Building2,
    ChevronDown,
    ChevronRight,
    Clock3,
    FilterX,
    LogIn,
    LogOut,
    Monitor,
    Search,
    ShieldCheck,
    SlidersHorizontal,
    UserRound,
} from 'lucide-react';
import AppLayout from '../../../Layouts/AppLayout';
import {
    Badge,
    Button,
    Card,
    EmptyState,
    Field,
    PageHeader,
    Pagination,
    Select,
    StatCard,
    Tabs,
} from '../../../components/ui';
import { formatDateTime, formatNumber, relativeTime } from '../../../lib/utils';

const ACTION_OPTIONS = [
    { value: 'referral', label: 'Referral events' },
    { value: 'transfer', label: 'Transfer events' },
    { value: 'bed', label: 'Bed updates' },
    { value: 'hospital', label: 'Hospital profiles' },
    { value: 'user', label: 'User accounts' },
    { value: 'settings', label: 'Platform settings' },
];

function actionTone(action) {
    if (action.startsWith('referral')) return 'brand';
    if (action.startsWith('transfer')) return 'sky';
    if (action.startsWith('bed')) return 'teal';
    if (action.startsWith('hospital')) return 'violet';
    if (action.startsWith('user')) return 'indigo';
    if (action.startsWith('settings')) return 'amber';
    return 'slate';
}

export default function AdminAuditIndex({ logs, logins = [], filters = {}, hospitals = [], isNetworkUser = false }) {
    const [tab, setTab] = useState(filters.tab === 'logins' ? 'logins' : 'logs');
    const [values, setValues] = useState({
        search: filters.search ?? '',
        action: filters.action ?? '',
        hospital_id: filters.hospital_id ?? '',
    });
    const [expanded, setExpanded] = useState(null);

    const successfulLogins = logins.filter((log) => log.success).length;
    const failedLogins = logins.filter((log) => !log.success).length;

    const visit = (nextTab, nextValues) => {
        const params = Object.fromEntries(
            Object.entries({ ...nextValues, tab: nextTab }).filter(([, value]) => value !== '' && value !== null),
        );
        router.get('/admin/audit', params, { preserveState: true, preserveScroll: true, replace: true });
    };

    const changeTab = (nextTab) => {
        setTab(nextTab);
        visit(nextTab, values);
    };

    const apply = (event) => {
        event.preventDefault();
        visit(tab, values);
    };

    const reset = () => {
        setValues({ search: '', action: '', hospital_id: '' });
        setExpanded(null);
        visit('logs', { search: '', action: '', hospital_id: '' });
        setTab('logs');
    };

    return (
        <AppLayout>
            <Head title="Audit trail" />

            <div className="space-y-6">
                <PageHeader
                    eyebrow="Administration"
                    title="Audit trail"
                    description="Review security-relevant changes and sign-in activity. Audit entries are generated by the platform and cannot be edited."
                    actions={<Badge tone="brand" dot>{isNetworkUser ? 'Network scope' : 'Hospital scope'}</Badge>}
                />

                <div className="grid gap-3 sm:grid-cols-3">
                    <StatCard label="Audit events" value={formatNumber(logs?.total)} hint="Matching current filters" icon={ShieldCheck} tone="brand" />
                    <StatCard label="Successful sign-ins" value={formatNumber(successfulLogins)} hint="Latest 20 records" icon={LogIn} tone="emerald" />
                    <StatCard label="Failed sign-ins" value={formatNumber(failedLogins)} hint="Latest 20 records" icon={LogOut} tone={failedLogins ? 'rose' : 'slate'} />
                </div>

                <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
                    <Tabs
                        value={tab}
                        onChange={changeTab}
                        options={[
                            { value: 'logs', label: 'Audit log', count: logs?.total },
                            { value: 'logins', label: 'Sign-in activity', count: logins?.length },
                        ]}
                    />
                    {tab === 'logs' && <p className="text-[10px] text-ink-400">Changes are stored as structured JSON for review.</p>}
                </div>

                {tab === 'logs' ? (
                    <>
                        <Card className="p-4 sm:p-5">
                            <form onSubmit={apply} className="flex flex-col gap-3 lg:flex-row lg:items-end">
                                <Field label="Search" htmlFor="audit-search" className="lg:w-72">
                                    <div className="relative">
                                        <Search className="pointer-events-none absolute top-1/2 left-3.5 size-4 -translate-y-1/2 text-ink-400" />
                                        <input
                                            id="audit-search"
                                            type="search"
                                            value={values.search}
                                            onChange={(event) => setValues((current) => ({ ...current, search: event.target.value }))}
                                            placeholder="Action, user name, or email"
                                            className="input pl-10"
                                        />
                                    </div>
                                </Field>

                                <Field label="Action group" htmlFor="audit-action" className="lg:w-52">
                                    <Select
                                        id="audit-action"
                                        value={values.action}
                                        onChange={(event) => setValues((current) => ({ ...current, action: event.target.value }))}
                                    >
                                        <option value="">All actions</option>
                                        {ACTION_OPTIONS.map((option) => (
                                            <option key={option.value} value={option.value}>
                                                {option.label}
                                            </option>
                                        ))}
                                    </Select>
                                </Field>

                                {hospitals.length > 0 && (
                                    <Field label="Hospital" htmlFor="audit-hospital" className="lg:w-60">
                                        <Select
                                            id="audit-hospital"
                                            value={values.hospital_id}
                                            onChange={(event) => setValues((current) => ({ ...current, hospital_id: event.target.value }))}
                                        >
                                            <option value="">All hospitals</option>
                                            {hospitals.map((hospital) => (
                                                <option key={hospital.id} value={hospital.id}>
                                                    {hospital.short_name || hospital.name}
                                                </option>
                                            ))}
                                        </Select>
                                    </Field>
                                )}

                                <div className="flex items-center gap-2 lg:ml-auto">
                                    <Button type="button" variant="ghost" size="sm" onClick={reset}>
                                        <FilterX className="size-4" />
                                        Reset
                                    </Button>
                                    <Button type="submit" size="sm">
                                        <SlidersHorizontal className="size-4" />
                                        Apply
                                    </Button>
                                </div>
                            </form>
                        </Card>

                        <Card className="overflow-hidden">
                            {logs?.data?.length ? (
                                <>
                                    <div className="overflow-x-auto">
                                        <table className="table">
                                            <thead>
                                                <tr>
                                                    <th aria-label="Expand" />
                                                    <th>Event</th>
                                                    <th>User</th>
                                                    <th>Subject</th>
                                                    <th>Hospital</th>
                                                    <th>IP address</th>
                                                    <th>Recorded</th>
                                                </tr>
                                            </thead>
                                            <tbody>
                                                {logs.data.map((log) => {
                                                    const isExpanded = expanded === log.id;
                                                    const hasChanges = log.changes && Object.keys(log.changes).length > 0;

                                                    return (
                                                        <Fragment key={log.id}>
                                                            <tr
                                                                className={hasChanges ? 'cursor-pointer' : undefined}
                                                                onClick={() => hasChanges && setExpanded(isExpanded ? null : log.id)}
                                                            >
                                                                <td className="w-8">
                                                                    {hasChanges ? (
                                                                        <button
                                                                            type="button"
                                                                            className="btn-icon size-7"
                                                                            aria-label={isExpanded ? 'Collapse changes' : 'Show changes'}
                                                                            aria-expanded={isExpanded}
                                                                        >
                                                                            {isExpanded ? <ChevronDown className="size-4" /> : <ChevronRight className="size-4" />}
                                                                        </button>
                                                                    ) : (
                                                                        <span className="block size-7" />
                                                                    )}
                                                                </td>
                                                                <td>
                                                                    <Badge tone={actionTone(log.action)}>{log.action_label}</Badge>
                                                                    <span className="mt-1 block font-mono text-[10px] text-ink-400">{log.action}</span>
                                                                </td>
                                                                <td>
                                                                    <span className="block max-w-40 truncate text-xs font-semibold text-ink-800">{log.user}</span>
                                                                    <span className="mt-0.5 block max-w-48 truncate text-[10px] text-ink-400">{log.user_email || 'No account'}</span>
                                                                </td>
                                                                <td>
                                                                    {log.subject_type ? (
                                                                        <>
                                                                            <span className="block text-xs text-ink-700">{log.subject_type}</span>
                                                                            <span className="mt-0.5 block font-mono text-[10px] text-ink-400">#{log.subject_id}</span>
                                                                        </>
                                                                    ) : (
                                                                        <span className="text-xs text-ink-400">Platform</span>
                                                                    )}
                                                                </td>
                                                                <td>
                                                                    <span className="flex items-center gap-1.5 text-xs text-ink-600">
                                                                        <Building2 className="size-3 shrink-0 text-ink-400" />
                                                                        <span className="max-w-40 truncate">{log.hospital || 'All hospitals'}</span>
                                                                    </span>
                                                                </td>
                                                                <td>
                                                                    <span className="font-mono text-[10px] text-ink-500">{log.ip_address || '—'}</span>
                                                                </td>
                                                                <td>
                                                                    <span className="block whitespace-nowrap text-xs text-ink-600">{relativeTime(log.created_at)}</span>
                                                                    <span className="mt-0.5 block whitespace-nowrap text-[10px] text-ink-400">{formatDateTime(log.created_at)}</span>
                                                                </td>
                                                            </tr>
                                                            {isExpanded && hasChanges && (
                                                                <tr>
                                                                    <td colSpan={7} className="bg-ink-50/70">
                                                                        <div className="rounded-xl border border-ink-100 bg-white p-3">
                                                                            <p className="mb-2 text-[10px] font-semibold tracking-wide text-ink-500 uppercase">
                                                                                Structured change data
                                                                            </p>
                                                                            <pre className="max-h-80 overflow-auto rounded-lg bg-ink-950 p-3 font-mono text-[11px] leading-5 text-brand-100">
                                                                                {JSON.stringify(log.changes, null, 2)}
                                                                            </pre>
                                                                        </div>
                                                                    </td>
                                                                </tr>
                                                            )}
                                                        </Fragment>
                                                    );
                                                })}
                                            </tbody>
                                        </table>
                                    </div>
                                    <div className="border-t border-ink-100 px-5 py-4">
                                        <Pagination paginator={logs} />
                                    </div>
                                </>
                            ) : (
                                <EmptyState
                                    icon={ShieldCheck}
                                    title="No audit events match these filters"
                                    description="Try a different action group, hospital, or search term."
                                    action={
                                        <Button variant="secondary" onClick={reset}>
                                            Clear filters
                                        </Button>
                                    }
                                />
                            )}
                        </Card>
                    </>
                ) : (
                    <Card className="overflow-hidden">
                        {logins.length ? (
                            <div className="overflow-x-auto">
                                <table className="table">
                                    <thead>
                                        <tr>
                                            <th>Account</th>
                                            <th>Result</th>
                                            <th>IP address</th>
                                            <th>When</th>
                                        </tr>
                                    </thead>
                                    <tbody>
                                        {logins.map((log) => (
                                            <tr key={log.id}>
                                                <td>
                                                    <div className="flex items-center gap-2.5">
                                                        <span className="flex size-8 items-center justify-center rounded-lg bg-ink-100 text-ink-500">
                                                            <UserRound className="size-4" />
                                                        </span>
                                                        <span className="max-w-60 truncate text-xs font-semibold text-ink-800">{log.email}</span>
                                                    </div>
                                                </td>
                                                <td>
                                                    <Badge tone={log.success ? 'emerald' : 'rose'} dot>
                                                        {log.success ? 'Successful' : 'Failed'}
                                                    </Badge>
                                                </td>
                                                <td>
                                                    <span className="flex items-center gap-1.5 font-mono text-[10px] text-ink-500">
                                                        <Monitor className="size-3 text-ink-400" />
                                                        {log.ip_address || '—'}
                                                    </span>
                                                </td>
                                                <td>
                                                    <span className="block whitespace-nowrap text-xs text-ink-600">{relativeTime(log.created_at)}</span>
                                                    <span className="mt-0.5 block whitespace-nowrap text-[10px] text-ink-400">{formatDateTime(log.created_at)}</span>
                                                </td>
                                            </tr>
                                        ))}
                                    </tbody>
                                </table>
                                <div className="flex items-center gap-2 border-t border-ink-100 px-5 py-3 text-[10px] text-ink-400">
                                    <Clock3 className="size-3.5" />
                                    Showing the latest {formatNumber(logins.length)} sign-in records. Email filtering follows your hospital scope.
                                </div>
                            </div>
                        ) : (
                            <EmptyState icon={LogIn} title="No sign-in records" description="Authentication activity will appear here once users sign in." />
                        )}
                    </Card>
                )}

                <p className="text-[11px] leading-5 text-ink-400">
                    Audit retention and privacy: records contain the acting account, hospital context, IP address, and structured changes. Patient clinical details are never
                    written to the audit log.
                </p>
            </div>
        </AppLayout>
    );
}
